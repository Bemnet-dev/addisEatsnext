import { ImageResponse } from "next/og";
import { getDishes } from "@/lib/dishes";
import { photoDataUri } from "@/lib/og-photo";
import { toSlug } from "../slug";

export const size = {
  width: 1200,
  height: 630,
};

export const contentType = "image/png";

export const alt = "Addis Eats dish photo";

/**
 * Per-dish social preview (1200x630): photo on the right, name + description +
 * price on the left.
 *
 * Two Satori constraints are easy to hit here:
 *  - display values must be "flex" | "block" | "contents" | "none" |
 *    "-webkit-box"; "inline-flex" throws (this route returned 500 before).
 *  - WebP cannot be decoded, so the photo is the JPEG generated by
 *    `npm run og:images`. A missing file yields a text-only card, never a 500.
 */
export default async function Image({ params }) {
  const { slug } = await params;
  const dishes = await getDishes();
  const dish = dishes.find((item) => toSlug(item.name) === slug);

  if (!dish) {
    return new Response("Dish not found", { status: 404 });
  }

  // JPEG produced by `npm run og:images` (Satori cannot decode WebP).
  const photo = await photoDataUri(`/og/dishes/${slug}.jpg`);

  return new ImageResponse(
    (
      <div
        style={{
          display: "flex",
          width: "100%",
          height: "100%",
          background: "linear-gradient(135deg, #111827 0%, #1f2937 45%, #0f172a 100%)",
          color: "#f8fafc",
          fontFamily: "sans-serif",
          overflow: "hidden",
        }}
      >
        <div
          style={{
            display: "flex",
            flex: 1,
            flexDirection: "column",
            justifyContent: "space-between",
            padding: "56px 48px 56px 64px",
          }}
        >
          <div
            style={{
              display: "flex",
              alignItems: "center",
              justifyContent: "space-between",
              fontSize: 24,
              letterSpacing: 5,
              color: "#fbbf24",
              textTransform: "uppercase",
            }}
          >
            <span>Addis Eats</span>
            <span>{dish.category}</span>
          </div>

          <div
            style={{
              display: "flex",
              flexDirection: "column",
              gap: 18,
            }}
          >
            <div
              style={{
                display: "flex",
                alignSelf: "flex-start",
                padding: "8px 18px",
                borderRadius: 999,
                background: "rgba(251, 191, 36, 0.14)",
                color: "#fbbf24",
                fontSize: 22,
                fontWeight: 700,
              }}
            >
              Fresh from the kitchen
            </div>
            <div
              style={{
                display: "flex",
                fontSize: dish.name.length > 22 ? 56 : 68,
                lineHeight: 1.05,
                fontWeight: 800,
                maxWidth: 640,
              }}
            >
              {dish.name}
            </div>
            <div
              style={{
                display: "flex",
                fontSize: 27,
                lineHeight: 1.35,
                color: "#d1d5db",
                maxWidth: 640,
              }}
            >
              {dish.description}
            </div>
          </div>

          <div
            style={{
              display: "flex",
              alignItems: "center",
              justifyContent: "space-between",
              width: "100%",
              borderTop: "1px solid rgba(255,255,255,0.2)",
              paddingTop: 24,
              fontSize: 28,
              color: "#e5e7eb",
            }}
          >
            <span>Addis Eats</span>
            <span style={{ color: "#fbbf24", fontWeight: 700 }}>{dish.price} Birr</span>
          </div>
        </div>

        {photo && (
          // Satori cannot render next/image, and the photo is decorative
          // (the card's meaning is in the text, exposed via og:image:alt).
          // eslint-disable-next-line @next/next/no-img-element
          <img
            src={photo}
            alt=""
            width={430}
            height={630}
            style={{
              width: 430,
              height: 630,
              objectFit: "cover",
            }}
          />
        )}
      </div>
    ),
    {
      width: size.width,
      height: size.height,
    }
  );
}
